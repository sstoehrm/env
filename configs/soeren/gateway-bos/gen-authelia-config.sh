#!/usr/bin/env bash
# Print the Authelia configuration of the simpleviz gateway.
#
# usage: gen-authelia-config.sh > configuration.yml
#
# Env: GATEWAY_DOMAIN (default bos.home.arpa), PORTAL_PORT (default
# 8360), POLICY (one_factor, the default, or two_factor for a TOTP second
# factor).
#
# Secrets aren't in here: authelia.sh hands them over as *_FILE variables.
# The session cookie belongs to GATEWAY_DOMAIN itself, never its parent
# (home.arpa would send it to every such name on the LAN); browsers send it to
# every port of that host, so one login covers all gateway ports.

set -euo pipefail

domain="${GATEWAY_DOMAIN:-bos.home.arpa}"
portal_port="${PORTAL_PORT:-8360}"
policy="${POLICY:-one_factor}"

[[ "$domain" == *.* && "$domain" =~ ^[A-Za-z0-9.-]+$ ]] \
  || { echo "gen-authelia-config: GATEWAY_DOMAIN needs a dot (Authelia refuses single-label names)" >&2; exit 1; }
[[ "$policy" == one_factor || "$policy" == two_factor ]] \
  || { echo "gen-authelia-config: POLICY must be one_factor or two_factor" >&2; exit 1; }

cat <<EOF
# Generated by configs/soeren/gateway-bos/gen-authelia-config.sh — do not edit.
theme: auto

server:
  address: 'tcp://0.0.0.0:9091/'

log:
  level: info

authentication_backend:
  # logins are managed with set-auth.sh; this folder is mounted read-only
  password_reset:
    disable: true
  password_change:
    disable: true
  file:
    path: /config/users_database.yml
    watch: true

access_control:
  default_policy: deny
  rules:
    - domain: '$domain'
      policy: $policy

session:
  cookies:
    - domain: '$domain'
      authelia_url: 'https://$domain:$portal_port'
      expiration: '1d'
      inactivity: '4h'
      remember_me: '1M'

regulation:
  max_retries: 5
  find_time: '2m'
  ban_time: '15m'

totp:
  issuer: '$domain'

storage:
  local:
    path: /data/db.sqlite3

# no mail server: one-time codes (e.g. for registering TOTP) land in this
# file — read it with: sudo cat /var/lib/gateway-bos-authelia/notification.txt
notifier:
  filesystem:
    filename: /data/notification.txt
EOF
