#!/usr/bin/env bash
# Print a Caddyfile that puts an HTTPS proxy, behind an Authelia login, in
# front of every simpleviz port.
#
# usage: gen-caddyfile.sh <cert-file> <key-file> > Caddyfile
#
# simpleviz serves each instance on a random port in 7370-7469, bound to
# 127.0.0.1, below a secret token (http://localhost:<port>/<token>/). This
# opens https://<domain>:<port + OFFSET>/<token>/ for each of them
# (default OFFSET 1000 -> 8370-8469). Paths pass through untouched: the
# token redirect is an absolute /<token>/, so no prefix routing.
#
# Login: the Authelia portal is https://<domain>:$PORTAL_PORT (default
# 8360). Every other request reaches simpleviz only after forward_auth has
# asked Authelia (at $AUTHELIA_UPSTREAM, default 127.0.0.1:9091); with
# Authelia down nothing gets through.
#
# simpleviz guards itself against non-local requests, so per port:
#  - Host is rewritten to localhost:<port> (else 403 on every request)
#  - Origin is rewritten to http://localhost:<port> only when it is this
#    gateway's own https://<host:port>, i.e. a same-origin write or
#    websocket from the proxied page. Any other Origin passes unchanged,
#    so simpleviz still refuses cross-site writes with 403.

set -euo pipefail

usage="usage: gen-caddyfile.sh <cert-file> <key-file>"
cert="${1:?$usage}"
key="${2:?$usage}"
first="${SIMPLEVIZ_FIRST_PORT:-7370}"
last="${SIMPLEVIZ_LAST_PORT:-7469}"
offset="${OFFSET:-1000}"
portal_port="${PORTAL_PORT:-8360}"
authelia="${AUTHELIA_UPSTREAM:-127.0.0.1:9091}"

# the public range must not overlap simpleviz's own: its free-port probe
# would then find Caddy's listeners taken
if (( first + offset <= last && last + offset >= first )); then
  echo "gen-caddyfile: OFFSET $offset makes the gateway ports overlap $first-$last" >&2
  exit 1
fi
if (( (portal_port >= first && portal_port <= last) ||
      (portal_port >= first + offset && portal_port <= last + offset) )); then
  echo "gen-caddyfile: PORTAL_PORT $portal_port lies in a simpleviz or gateway range" >&2
  exit 1
fi

cat <<EOF
# Generated by configs/soeren/gateway-bos/gen-caddyfile.sh — do not edit.
# simpleviz gateway: https://<domain>:<port + $offset> -> http://127.0.0.1:<port>
# login portal (Authelia): https://<domain>:$portal_port

{
	# certificates are supplied below; no ACME, no :80 redirect server
	auto_https off
	admin localhost:2019
}

https://:$portal_port {
	tls $cert $key
	reverse_proxy $authelia
}
EOF

for (( port = first; port <= last; port++ )); do
  cat <<EOF

https://:$(( port + offset )) {
	tls $cert $key
	@same_origin expression {http.request.header.Origin} == "https://" + {http.request.hostport}
	handle @same_origin {
		route {
			forward_auth $authelia {
				uri /api/authz/forward-auth
			}
			reverse_proxy 127.0.0.1:$port {
				header_up Host localhost:$port
				header_up Origin http://localhost:$port
			}
		}
	}
	handle {
		route {
			forward_auth $authelia {
				uri /api/authz/forward-auth
			}
			reverse_proxy 127.0.0.1:$port {
				header_up Host localhost:$port
			}
		}
	}
}
EOF
done
