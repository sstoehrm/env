#!/usr/bin/env bash
# Add a gateway login to Authelia, or change its password.
#
# usage: set-auth.sh [user]        (default user: $USER)
#
# Asks for the password twice and stores only its bcrypt hash (made by
# `caddy hash-password`, which reads it from stdin) in
# $CONFIG_DIR/users_database.yml (default /etc/caddy/gateway-bos/authelia).
# The source of truth is $CONFIG_DIR/users (user:hash lines); the YAML is
# rebuilt from it. Authelia watches the file, so no restart is needed.

set -euo pipefail

CONFIG_DIR="${CONFIG_DIR:-/etc/caddy/gateway-bos/authelia}"
CADDY="${CADDY:-caddy}"
user="${1:-$USER}"

[[ "$user" =~ ^[A-Za-z0-9._-]+$ ]] \
  || { echo "set-auth: user may hold only letters, digits and . _ -" >&2; exit 1; }
command -v "${CADDY%% *}" >/dev/null || { echo "set-auth: caddy not found — run setup.sh" >&2; exit 1; }

read -rsp "Password for $user: " pw; echo
read -rsp "Repeat: " pw2; echo
[[ "$pw" == "$pw2" ]] || { echo "set-auth: passwords differ" >&2; exit 1; }
(( ${#pw} >= 12 )) || { echo "set-auth: use at least 12 characters" >&2; exit 1; }

# via stdin, so the password never shows up in a process list
hash="$(printf '%s\n' "$pw" | $CADDY hash-password)"
unset pw pw2
[[ "$hash" == \$2* ]] || { echo "set-auth: caddy hash-password failed" >&2; exit 1; }

# as root for the default folder, as you for one of yours
as=()
[[ -w "$CONFIG_DIR" ]] || as=(sudo)

lines="$(mktemp)"; yaml="$(mktemp)"
trap 'rm -f "$lines" "$yaml"' EXIT
{ "${as[@]}" cat "$CONFIG_DIR/users" 2>/dev/null || true; } | grep -v "^$user:" > "$lines" || true
echo "$user:$hash" >> "$lines"

{
  echo "# Generated by configs/soeren/gateway-bos/set-auth.sh — rerun it to change."
  echo "users:"
  while IFS=: read -r u h; do
    [[ -n "$u" ]] || continue
    printf "  %s:\n    displayname: '%s'\n    password: '%s'\n" "$u" "$u" "$h"
  done < "$lines"
} > "$yaml"

if (( ${#as[@]} )); then
  sudo install -m 640 -o root -g caddy "$lines" "$CONFIG_DIR/users"
  sudo install -m 640 -o root -g caddy "$yaml" "$CONFIG_DIR/users_database.yml"
else
  install -m 600 "$lines" "$CONFIG_DIR/users"
  install -m 600 "$yaml" "$CONFIG_DIR/users_database.yml"
fi
echo "WROTE $CONFIG_DIR/users_database.yml (user $user)"
